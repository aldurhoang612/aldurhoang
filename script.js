// DOM References
const gridEl = document.getElementById('projects-grid');
const filterBtns = document.querySelectorAll('.filter-btn');
const searchInput = document.getElementById('project-search');
const modalEl = document.getElementById('project-modal');
const modalContentEl = document.getElementById('modal-content');
const modalCloseBtn = document.getElementById('modal-close');

let activeCategory = 'all';
let searchQuery = '';

function updateCategoryCounts() {
  const counts = {
    all: PROJECTS.length,
    branding: PROJECTS.filter((p) => p.category === 'branding').length,
    motion: PROJECTS.filter((p) => p.category === 'motion').length,
    '3d': PROJECTS.filter((p) => p.category === '3d').length,
    photography: PROJECTS.filter((p) => p.category === 'photography').length
  };

  Object.entries(counts).forEach(([key, val]) => {
    const badge = document.getElementById(`count-${key}`);
    if (badge) badge.textContent = val;
  });
}

function renderProjects() {
  const q = searchQuery.trim().toLowerCase();

  const filtered = PROJECTS.filter((project) => {
    const matchesCat = activeCategory === 'all' || project.category === activeCategory;
    const matchesSearch =
      !q ||
      project.title.toLowerCase().includes(q) ||
      project.client.toLowerCase().includes(q) ||
      project.summary.toLowerCase().includes(q) ||
      project.tools.some((t) => t.toLowerCase().includes(q));
    return matchesCat && matchesSearch;
  });

  if (filtered.length === 0) {
    gridEl.innerHTML = `
      <div style="grid-column: 1 / -1; text-align: center; padding: 48px 20px; color: var(--text-secondary);">
        <p>No projects matched your filter. Try clearing the search box or switching categories.</p>
      </div>
    `;
    return;
  }

  gridEl.innerHTML = filtered
    .map(
      (project) => `
      <article class="project-card" data-project-id="${project.id}" tabindex="0" role="button" aria-label="View case study: ${project.title}">
        <div class="project-thumb-wrap">
          <img src="${project.thumb}" alt="${project.title}" class="project-thumb" loading="lazy" />
          <div class="project-badges">
            <span class="project-cat-badge">${project.categoryLabel}</span>
            <span class="project-year-badge">${project.year}</span>
          </div>
        </div>
        <div class="project-body">
          <span class="project-client">${project.client}</span>
          <h3 class="project-title">${project.title}</h3>
          <p class="project-summary">${project.summary}</p>
          <div class="project-footer">
            <div class="project-tools">
              ${project.tools
                .slice(0, 3)
                .map((tool) => `<span class="mini-tag">${tool}</span>`)
                .join('')}
            </div>
            <span class="view-case-btn">Case Study ↗</span>
          </div>
        </div>
      </article>
    `
    )
    .join('');

  gridEl.querySelectorAll('.project-card').forEach((card) => {
    card.addEventListener('click', () => openProjectModal(card.dataset.projectId));
    card.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        openProjectModal(card.dataset.projectId);
      }
    });
  });
}

function openProjectModal(projectId) {
  const project = PROJECTS.find((p) => p.id === projectId);
  if (!project) return;

  const videoBlock = project.video
    ? `
      <video controls autoplay muted loop playsinline preload="metadata">
        <source src="${project.video}" type="video/mp4" />
      </video>
    `
    : '';

  const imagesHtml = project.gallery
    .map(
      (imgSrc, idx) =>
        `<img src="${imgSrc}" alt="${project.title} — Spread ${idx + 1}" loading="lazy" />`
    )
    .join('');

  modalContentEl.innerHTML = `
    <div class="modal-header">
      <div class="modal-meta-row">
        <span class="tag-pill tag-accent">${project.categoryLabel}</span>
        <span class="project-year-badge">${project.year}</span>
      </div>
      <h2 id="modal-title" class="modal-title">${project.title}</h2>
      <p class="modal-desc">${project.description}</p>

      <div class="modal-highlights">
        <div class="highlight-box">
          <span>CLIENT / PARTNER</span>
          <strong>${project.client}</strong>
        </div>
        <div class="highlight-box">
          <span>ROLE &amp; TOOLS</span>
          <strong>${project.role} · ${project.tools.join(', ')}</strong>
        </div>
        <div class="highlight-box">
          <span>OUTCOME &amp; IMPACT</span>
          <strong>${project.impact}</strong>
        </div>
      </div>
    </div>

    <div class="modal-gallery">
      ${videoBlock}
      ${imagesHtml}
    </div>
  `;

  modalEl.classList.add('open');
  modalEl.setAttribute('aria-hidden', 'false');
  document.body.style.overflow = 'hidden';
}

function closeProjectModal() {
  modalEl.classList.remove('open');
  modalEl.setAttribute('aria-hidden', 'true');
  modalContentEl.innerHTML = '';
  document.body.style.overflow = '';
}

// Event Listeners
filterBtns.forEach((btn) => {
  btn.addEventListener('click', () => {
    filterBtns.forEach((b) => b.classList.remove('active'));
    btn.classList.add('active');
    activeCategory = btn.dataset.filter;
    renderProjects();
  });
});

if (searchInput) {
  searchInput.addEventListener('input', (e) => {
    searchQuery = e.target.value;
    renderProjects();
  });
}

modalCloseBtn.addEventListener('click', closeProjectModal);
modalEl.addEventListener('click', (e) => {
  if (e.target === modalEl) closeProjectModal();
});

window.addEventListener('keydown', (e) => {
  if (e.key === 'Escape' && modalEl.classList.contains('open')) {
    closeProjectModal();
  }
});

// Hover-to-play videos in Motion & 3D Lab
document.querySelectorAll('.hover-video').forEach((video) => {
  const card = video.closest('.video-card');
  if (!card) return;
  card.addEventListener('mouseenter', () => {
    video.play().catch(() => {});
  });
  card.addEventListener('mouseleave', () => {
    video.pause();
  });
});

// Initialize
updateCategoryCounts();
renderProjects();
