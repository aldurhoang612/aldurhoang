  const titleText = tObj(project.title);
  const overviewText = tObj(project.overview) || tObj(project.summary);
  const highlightsArr = (project.highlights && (project.highlights[currentLang] || project.highlights.en)) || [];
  const catLabel = CATEGORY_LABELS[project.category]
